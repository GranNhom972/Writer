//! Document sharing: `token_session`, participants and permissions.
//!
//! A **session** gives a document a name chosen by the client (`token_session`)
//! and attaches to it the list of people who may access it, with each person's
//! e-mail address and permission.
//!
//! ## Two identifiers, two roles
//!
//! - `token_session` **names** the session. It is public, sent by e-mail or in a
//!   link, and gives no right on its own.
//! - **being on the participant list** opens access and sets the permission.
//!   Knowing the token is therefore not enough.
//! - `doc_id` is still generated by the server (UUIDv7): it addresses the document
//!   in storage and in the sync WebSocket.
//!
//! The token must nevertheless be **hard to guess** (`MIN_TOKEN_LEN`): it reveals
//! that a session exists, and participants' addresses are masked when read so that
//! this existence does not become a directory leak.

