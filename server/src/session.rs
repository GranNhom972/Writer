/// Minimum length of a `token_session`. A short token could be enumerated: the
/// existence of a session, and so the make-up of a team, could be guessed.
pub const MIN_TOKEN_LEN: usize = 12;
pub const MAX_TOKEN_LEN: usize = 128;
pub const MAX_PARTICIPANTS: usize = 200;
const MAX_TITLE_LEN: usize = 200;
const MAX_EMAIL_LEN: usize = 254;

// ── Model ────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Participant {
    pub user_id: String,
    pub email: String,
    pub permission: String,
}

impl Participant {
    pub fn scope(&self) -> Scope {
        // An unreadable permission MUST NOT grant more rights than what is written:
        // when in doubt, read-only.
        Scope::parse(&self.permission).unwrap_or(Scope::Read)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SessionRecord {
    pub token_session: String,
    pub doc_id: Uuid,
    pub title: String,
    pub created_at: String,
    pub created_by: String,
    pub participants: Vec<Participant>,
}

impl SessionRecord {
    pub fn find_by_email(&self, email: &str) -> Option<&Participant> {
        let needle = email.trim().to_ascii_lowercase();
        self.participants
            .iter()
            .find(|p| p.email.to_ascii_lowercase() == needle)
    }

    pub fn find_by_user(&self, user_id: &str) -> Option<&Participant> {
        self.participants.iter().find(|p| p.user_id == user_id)
    }
}

// ── Input validation ─────────────────────────────────────────────────────────

/// An acceptable `token_session`. It is used as a file name, so nothing in it may
/// be able to leave the sessions directory.
pub fn valid_token(token: &str) -> bool {
    token.len() >= MIN_TOKEN_LEN
        && token.len() <= MAX_TOKEN_LEN
        && token
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// A deliberately basic check: it rejects absurd input without claiming to decide
/// what a valid address is. Only actually sending a message proves that.
fn valid_email(email: &str) -> bool {
    if email.is_empty() || email.len() > MAX_EMAIL_LEN || email.chars().any(char::is_whitespace) {
        return false;
    }
    match email.split_once('@') {
        Some((local, domain)) => {
            !local.is_empty()
                && domain.contains('.')
                && !domain.starts_with('.')
                && !domain.ends_with('.')
        }
        None => false,
    }
}

/// Technical id derived from the address when the client does not supply one.
fn user_id_from_email(email: &str) -> Option<String> {
    let local = email.split('@').next()?;
    let id: String = local
        .to_ascii_lowercase()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' {
                c
            } else {
                '_'
            }
        })
        .collect();
    (!id.is_empty() && id.len() <= 64).then_some(id)
}

fn valid_user_id(user_id: &str) -> bool {
    !user_id.is_empty()
        && user_id.len() <= 64
        && user_id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// Masks an address for unauthenticated reads: `alice@example.org` becomes
/// `a****@example.org`. Confirming that a session exists MUST NOT hand out the
/// directory of its participants.
fn mask_email(email: &str) -> String {
    match email.split_once('@') {
        Some((local, domain)) => {
            let first = local.chars().next().unwrap_or('*');
            format!(
                "{first}{}@{domain}",
                "*".repeat(local.chars().count().saturating_sub(1))
            )
        }
        None => "***".to_string(),
    }
}

fn percent_encode(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for byte in raw.as_bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(*byte as char)
            }
            other => out.push_str(&format!("%{other:02X}")),
        }
    }
    out
}

/// The address that opens the document for a given person.
pub fn editor_path(token_session: &str, email: &str) -> String {
    format!(
        "/?session={}&email={}",
        percent_encode(token_session),
        percent_encode(email)
    )
}

