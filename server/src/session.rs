pub struct JoinSessionRequest {
    pub email: String,
}

#[derive(Debug, Deserialize)]
pub struct InviteRequest {
    pub email: String,
    #[serde(default)]
    pub user_id: Option<String>,
    #[serde(default)]
    pub permission: Option<String>,
}

